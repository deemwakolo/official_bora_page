// CONSTRUCTOR
// ───────────────────────────────────────────────────────────────────────────

/**
 * Build the initial lifecycle state for a song. A song starts ACTIVE.
 *
 * @param songId Stable identity.
 * @param k Optional historical upvotes. Defaults to 0.
 * @param persistentKura Optional starting balance. Defaults to 0.
 * @param history Optional retained history. Defaults to empty.
 */
export function createActiveSong(
  songId: string,
  k = 0,
  persistentKura = 0,
  history: readonly unknown[] = [],
): Result<LifecycleState, EngineError> {
  const state: LifecycleState = {
    songId,
    lifecycle: 'ACTIVE',
    k,
    persistentKura,
    history,
  };

  const valid = validateState(state);
  if (!valid.ok) {
    return { ok: false, error: valid.error };
  }

  return { ok: true, value: state };
}

// ───────────────────────────────────────────────────────────────────────────
// TRANSITIONS
// ───────────────────────────────────────────────────────────────────────────

/**
 * Vault a song: ACTIVE → VAULT.
 *
 * K, persistent Kura, and history are all RETAINED. A Vaulted song is merely
 * excluded from the active chart; nothing is deleted and nothing decays while
 * dormant (A8: no hidden decay accumulation while dead).
 *
 * @param state Current state. Not mutated.
 * @returns The Vaulted state, or an error for an invalid state or a no-op
 *   transition.
 */
export function vaultSong(
  state: LifecycleState,
): Result<LifecycleTransition, EngineError> {
  const valid = validateState(state);
  if (!valid.ok) {
    return { ok: false, error: valid.error };
  }

  const allowed = requireTransition(state, 'ACTIVE', 'VAULT', 'vault');
  if (!allowed.ok) {
    return { ok: false, error: allowed.error };
  }

  return {
    ok: true,
    value: {
      song: {
        songId: state.songId,
        lifecycle: 'VAULT',
        k: state.k, // retained
        persistentKura: state.persistentKura, // retained, NOT zeroed
        history: state.history, // retained by reference
      },
      transition: 'VAULTED',
      persistentKuraReset: false,
      seedCreated: false,
    },
  };
}

/**
 * Restore a song: VAULT → ACTIVE.
 *
 *   K = retained      persistent Kura = 0      seed = none
 *   history = retained
 *
 * This is NOT a re-entry. A returning song does not receive a new seed, a new
 * 72-hour runway, or a reset K. It resumes with an active persistent Kura of
 * exactly 0 and its full history intact — so it must earn its standing again
 * through real activity (A8).
 *
 * @param state Current Vaulted state. Not mutated.
 * @returns The Active state, or an error for an invalid state or a no-op
 *   transition.
 */
export function restoreSong(
  state: LifecycleState,
): Result<LifecycleTransition, EngineError> {
  const valid = validateState(state);
  if (!valid.ok) {
    return { ok: false, error: valid.error };
  }

  const allowed = requireTransition(state, 'VAULT', 'ACTIVE', 'restore');
  if (!allowed.ok) {
    return { ok: false, error: allowed.error };
  }

  return {
    ok: true,
    value: {
      song: {
        songId: state.songId, // identity preserved — never a new song
        lifecycle: 'ACTIVE',
        k: state.k, // retained
        persistentKura: 0, // A8: reset active persistent Kura
        history: state.history, // retained by reference
      },
      transition: 'RESTORED',
      persistentKuraReset: true,
      seedCreated: false, // never seeded on restore
    },
  };
}