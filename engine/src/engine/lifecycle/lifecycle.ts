/**
 * BORA Engine — song lifecycle (Vault) state
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * PHASE 13. The lifecycle state-transition layer.
 *
 *   ACTIVE ⇄ VAULT      (via `VAULT`, the contract's existing state name)
 *
 * ── VAULT IS EXCLUSION, NOT DELETION ───────────────────────────────────────
 *
 *   Vaulting removes a song from the ACTIVE chart. It erases nothing:
 *
 *     · K                       retained
 *     · persistent Kura         retained in the Vaulted state
 *     · historical records      retained (references, never filtered)
 *     · song identity           retained
 *
 *   The evaluation layers that exclude a Vaulted song — active C, XP, fresh
 *   Kura, decay, platform points, BORA Score, ranking — are LATER phases.
 *   This module performs no evaluation at all.
 *
 * ── RESTORE REWINDS ACTIVE SCORE, NEVER HISTORY ────────────────────────────
 *
 *     K = retained          persistent Kura = 0          seed = none
 *     history = retained    lifecycle = ACTIVE
 *
 *   The `persistentKuraReset` flag makes that rule EXPLICIT in the result, so
 *   a caller cannot mistake a restore for a fresh song: restore never
 *   constructs a new identity and never generates a seeded runway. It has no
 *   seed concept at all — see the dependency rule below.
 *
 * ── WHY INVALID TRANSITIONS ARE REJECTED ───────────────────────────────────
 *
 *   ACTIVE → ACTIVE and VAULT → VAULT are not transitions. Silently
 *   "succeeding" would hide a caller bug: a double-vault usually means an
 *   event handler fired twice, and a silent success would mask it. They return
 *   `ILLEGAL_LIFECYCLE_OPERATION` — an error code that already exists in the
 *   Phase 1 contract for exactly this meaning. No new code was invented.
 *
 * ── NO CLOCK, NO SEED ──────────────────────────────────────────────────────
 *
 *   Restore does not know what hour it is and does not call the seed module.
 *   It cannot: this file imports only `../types`, so there is no path to the
 *   seed mathematics at all.
 *
 * PURE: no mutation, no clock, no randomness, no seed, no ranking, no score,
 * no Kura math, no platform math, no simulation, no Supabase, no React.
 */

import type { SongLifecycle, Result, EngineError } from '../types';

/** A song's lifecycle-relevant state, plus retained references to history. */
export interface LifecycleState {
  /** Stable identity. Never regenerated by a lifecycle operation. */
  readonly songId: string;

  /** ACTIVE or VAULT. */
  readonly lifecycle: SongLifecycle;

  /**
   * Historical upvotes. Permanent and monotonic; unaffected by Vault or
   * restore (Contract 2, Contract Phase 5).
   */
  readonly k: number;

  /**
   * The persistent-Kura balance.
   *
   * RETAINED while VAULTED, and reset to exactly 0 on restore (A8). A Vaulted
   * song is excluded from the active chart, so its balance is not advancing;
   * it is preserved for audit and must not silently decay while dormant.
   */
  readonly persistentKura: number;

  /**
   * Historical engine records (hourly buckets, platform observations, …).
   *
   * Carried as an opaque retained reference. Lifecycle operations NEVER
   * inspect, filter, truncate, or copy this data — they pass it through
   * unchanged, which is precisely how "Vault is exclusion, not deletion" is
   * guaranteed rather than merely asserted.
   */
  readonly history: readonly unknown[];
}

/**
 * The outcome of a lifecycle transition.
 *
 * `persistentKuraReset` is explicit so the restore rule is visible to callers
 * and inspectable in the formula view: it is true exactly when a restore
 * zeroed the active persistent Kura.
 */
export interface LifecycleTransition {
  readonly song: LifecycleState;

  /** Which transition was performed. */
  readonly transition: 'VAULTED' | 'RESTORED';

  /** True when this transition reset persistent Kura to 0 (restore only). */
  readonly persistentKuraReset: boolean;

  /**
   * True when this transition granted a NEW seed. Always false: lifecycle
   * operations never seed, so this exists to make that observable.
   */
  readonly seedCreated: false;
}

// ───────────────────────────────────────────────────────────────────────────
// VALIDATION
// ───────────────────────────────────────────────────────────────────────────

function isNonNegativeFinite(value: unknown): value is number {
  return typeof value === 'number' && Number.isFinite(value) && value >= 0;
}

function reject<T>(
  code: EngineError['code'],
  message: string,
  context: Record<string, string>,
): Result<T, EngineError> {
  return { ok: false, error: { code, message, context } };
}

/**
 * Validate a lifecycle state before any transition is attempted.
 *
 * Nothing is coerced: an invalid K, persistent Kura, or lifecycle value
 * rejects the operation rather than being replaced with 0, which would
 * silently rewrite a song's history.
 */
function validateState(state: LifecycleState): Result<true, EngineError> {
  if (typeof state.songId !== 'string' || state.songId.length === 0) {
    return reject(
      'INVALID_SONG_ID',
      'songId must be a non-empty string. Lifecycle operations preserve ' +
        'song identity, so an empty id has no meaning.',
      { songId: String(state.songId) },
    );
  }

  if (!isNonNegativeFinite(state.k)) {
    return reject(
      'INVALID_K',
      'K must be a finite, non-negative number. Rejected rather than zeroed: ' +
        'K is permanent history and must never be rewritten by a lifecycle ' +
        'operation.',
      { songId: state.songId, k: String(state.k) },
    );
  }

  if (!isNonNegativeFinite(state.persistentKura)) {
    return reject(
      'INVALID_MEASUREMENT',
      'persistentKura must be a finite, non-negative number. Rejected rather ' +
        'than zeroed: a corrupt balance must stay visible instead of being ' +
        'silently repaired.',
      { songId: state.songId, persistentKura: String(state.persistentKura) },
    );
  }

  if (state.lifecycle !== 'ACTIVE' && state.lifecycle !== 'VAULT') {
    return reject(
      'ILLEGAL_LIFECYCLE_OPERATION',
      'lifecycle must be ACTIVE or VAULT. Rejected rather than defaulted, so ' +
        'an unknown state cannot be mistaken for an active song.',
      { songId: state.songId, lifecycle: String(state.lifecycle) },
    );
  }

  if (!Array.isArray(state.history)) {
    return reject(
      'INVALID_MEASUREMENT',
      'history must be an array of retained records. Rejected rather than ' +
        'replaced: Vault must retain history, never discard it.',
      { songId: state.songId },
    );
  }

  return { ok: true, value: true };
}

/** The transition a given operation requires as its starting state. */
function requireTransition(
  state: LifecycleState,
  from: SongLifecycle,
  to: SongLifecycle,
  verb: string,
): Result<true, EngineError> {
  if (state.lifecycle !== from) {
    return reject(
      'ILLEGAL_LIFECYCLE_OPERATION',
      `Cannot ${verb} a song whose lifecycle is ${state.lifecycle}; ` +
        `${verb} requires ${from}. A no-op transition is rejected rather than ` +
        'silently accepted, so a repeated event handler is not masked.',
      { songId: state.songId, from, to, actual: state.lifecycle },
    );
  }
  return { ok: true, value: true };
}

