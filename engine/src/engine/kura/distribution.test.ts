const H = 1000 as HourIndex;
const hour = (n: number) => n as HourIndex;

/** A song whose active window holds `hours` buckets each with `votes` upvotes. */
function songWith(
  id: string,
  hours: number,
  votes: number,
): ChartSongInput {
  const buckets: VoteBucket[] = [];
  for (let i = hours - 1; i >= 0; i--) {
    buckets.push({ ...emptyBucket(hour(H - i)), upvotes: votes });
  }
  return { id, buckets };
}

/** A song with explicit per-hour C, using the proven lattice. */
function songWithC(id: string, perHourC: number[], offset = 0): ChartSongInput {
  // Each lattice value is produced by a raw vote count, so the expected C is
  // derived from the SAME threshold table the engine uses.
  const votesForC = (c: number): number => {
    switch (c) {
      case 0: return 0;
      case 0.5: return 0; // achieved with 1..4 downvotes instead
      case 1: return 1;
      case 1.5: return 5; // 2 - 0.5
      case 2: return 5;
      default: throw new Error(`not on the lattice: ${c}`);
    }
  };
  const downForC = (c: number): number => (c === 0.5 ? 1 : 0);

  const buckets: VoteBucket[] = [];
  perHourC.forEach((c, idx) => {
    buckets.push({
      ...emptyBucket(hour(H - offset - idx)),
      upvotes: votesForC(c),
      downvotes: downForC(c),
    });
  });
  return { id, buckets };
}

/** Evaluate and unwrap, failing loudly with the engine's own error. */
function dist(population: ChartSongInput[]): ActiveDistribution {
  const r = evaluateActiveDistribution(population, H);
  if (!r.ok) throw new Error(r.error.message);
  return r.value;
}

function sum(arr: readonly number[]): number {
  return arr.reduce((a, b) => a + b, 0);
}

