/**
 * Extract one top-level function's full body from a module's source.
 *
 * Brace-counting is used deliberately rather than a marker search: a function's
 * real body ends at its own closing brace, and slicing on a newline pattern
 * would stop early at the first nested object literal.
 */
function functionBody(body: string, signature: string): string {
  const start = body.indexOf(signature);
  if (start < 0) throw new Error(`signature not found: ${signature}`);

  const open = body.indexOf('{', start);
  let depth = 0;

  for (let i = open; i < body.length; i++) {
    if (body[i] === '{') depth++;
    else if (body[i] === '}') {
      depth--;
      if (depth === 0) return body.slice(open, i + 1);
    }
  }

  throw new Error(`unbalanced body for: ${signature}`);
}

