/**
 * The reference hour every generated case is anchored at.
 *
 * A fixed anchor is deliberate: it makes every generated hour an absolute,
 * readable clock index (window 929..1000, expired 928, future 1001) instead of
 * an expression a reader would have to re-derive to understand a failure.
 */
export const CORPUS_HOUR = 1000;

/** The inclusive C window for CORPUS_HOUR: H-71 .. H. */
export const CORPUS_WINDOW_START = CORPUS_HOUR - 71;

/** A scenario with no songs and no closed hour. */
export function scenario(
  name: string,
  songs: readonly SpecSong[],
  closedHourC: number | null = null,
  referenceHour: number = CORPUS_HOUR,
): SpecScenario {
  return { name, referenceHour, closedHourC, songs };
}

/** `count` buckets spread across the window, each worth C = 2.0. */
export function fullTwoBuckets(count: number, from = CORPUS_WINDOW_START): SpecBucket[] {
  const out: SpecBucket[] = [];
  for (let i = 0; i < count; i++) {
    out.push({ hour: from + i, up: 5, down: 0 });
  }
  return out;
}

/** `count` SEED records across the window at a fixed C. */
export function seedRun(count: number, c: number, from = CORPUS_WINDOW_START): SpecSeed[] {
  const out: SpecSeed[] = [];
  for (let i = 0; i < count; i++) {
    out.push({ hour: from + i, c, source: 'SEED', archived: false });
  }
  return out;
}
/** A song with `n` full-strength (C = 2.0) hours at the window start. */
export function songWithC(id: string, n: number, k = 0, persistentKura = 0): SpecSong {
  return song(id, {
    k,
    persistentKura,
    buckets: fullTwoBuckets(n),
  });
}

/**
 * The deterministic conformance corpus.
 *
 * Every entry is hand-authored rather than sampled, so each case names the
 * contract rule it exists to probe. Randomised cases are added separately by
 * `buildRandomCorpus`; mixing them here would make a failing case number
 * uninterpretable.
 */
export function buildCorpus(): SpecScenario[] {
  const H = CORPUS_HOUR;
  const W = CORPUS_WINDOW_START;
  const cases: SpecScenario[] = [];

  // -- POPULATION -------------------------------------------------------------
  cases.push(scenario('population/0-songs', []));
  cases.push(scenario('population/1-song-no-data', [song('a')]));
  cases.push(
    scenario('population/2-songs', [songWithC('a', 3, 10), songWithC('b', 5, 20)]),
  );
  cases.push(
    scenario(
      'population/5-songs',
      [songWithC('a', 1, 5), songWithC('b', 2, 4), songWithC('c', 3, 3),
       songWithC('d', 4, 2), songWithC('e', 5, 1)],
    ),
  );
  cases.push(
    scenario(
      'population/10-songs',
      Array.from({ length: 10 }, (_, i) => songWithC(`s${i}`, i + 1, 100 - i)),
    ),
  );

  // -- HOURLY C ---------------------------------------------------------------
  cases.push(
    scenario('c/all-zero-no-buckets', [song('a'), song('b')]),
  );
  cases.push(
    scenario('c/one-active-hour', [
      song('a', { buckets: [{ hour: H, up: 5, down: 0 }] }),
      song('b'),
    ]),
  );
  cases.push(
    scenario('c/full-2.0', [
      song('a', { buckets: [{ hour: H, up: 9, down: 0 }] }),
      song('b', { buckets: [{ hour: H, up: 5, down: 0 }] }),
    ]),
  );
  cases.push(
    scenario('c/value-0.5', [
      song('a', { buckets: [{ hour: H, up: 0, down: 1 }] }),
      song('b', { buckets: [{ hour: H, up: 5, down: 0 }] }),
    ]),
  );
  cases.push(
    scenario('c/value-1.0', [
      song('a', { buckets: [{ hour: H, up: 1, down: 0 }] }),
      song('b', { buckets: [{ hour: H, up: 5, down: 0 }] }),
    ]),
  );
  cases.push(
    scenario('c/value-1.5', [
      song('a', { buckets: [{ hour: H, up: 5, down: 1 }] }),
      song('b', { buckets: [{ hour: H, up: 5, down: 0 }] }),
    ]),
  );
  cases.push(
    scenario('c/mixed', [
      song('a', { buckets: [
        { hour: W, up: 1, down: 0 }, { hour: W + 1, up: 5, down: 0 },
        { hour: W + 2, up: 0, down: 4 }, { hour: H, up: 4, down: 1 },
      ] }),
      song('b', { buckets: [{ hour: W + 3, up: 6, down: 0 }] }),
    ]),
  );
  cases.push(
    scenario('c/extreme-vote-counts', [
      song('a', { buckets: [{ hour: H, up: 1000000, down: 0 }] }),
      song('b', { buckets: [{ hour: H, up: 0, down: 1000000 }] }),
      song('c', { buckets: [{ hour: H, up: 4, down: 4 }] }),
    ]),
  );

  // -- WINDOW -----------------------------------------------------------------
  cases.push(
    scenario('window/exactly-72-hours', [
      song('a', { buckets: fullTwoBuckets(72, W) }),
      song('b'),
    ]),
  );
  cases.push(
    scenario('window/71-hours', [
      song('a', { buckets: fullTwoBuckets(71, W) }),
      song('b'),
    ]),
  );
  cases.push(
    scenario('window/73-hours-includes-expired', [
      song('a', { buckets: fullTwoBuckets(73, W - 1) }),
      song('b'),
    ]),
  );
  cases.push(
    scenario('window/sparse', [
      song('a', { buckets: [
        { hour: W, up: 5, down: 0 }, { hour: W + 40, up: 5, down: 0 },
        { hour: H, up: 5, down: 0 },
      ] }),
      song('b', { buckets: [{ hour: W + 70, up: 5, down: 0 }] }),
    ]),
  );
  cases.push(
    scenario('window/boundary-H-minus-71', [
      song('a', { buckets: [{ hour: W, up: 5, down: 0 }] }),
      song('b'),
    ]),
  );
  cases.push(
    scenario('window/expired-H-minus-72-only', [
      song('a', { buckets: [{ hour: H - 72, up: 5, down: 0 }] }),
      song('b', { buckets: [{ hour: H, up: 5, down: 0 }] }),
    ]),
  );
  cases.push(
    scenario('window/future-H-plus-1-only', [
      song('a', { buckets: [{ hour: H + 1, up: 5, down: 0 }] }),
      song('b', { buckets: [{ hour: H, up: 5, down: 0 }] }),
    ]),
  );

  return cases;
}
/**
 * Seed precedence cases (Phase 21 C3 / section 17).
 *
 * The single most important property in the whole phase: ACTUAL REPLACES SEED,
 * including when the ACTUAL value is 0. Every case below is built so that a
 * model which summed the two, or which treated actual-zero as "no actual",
 * would produce a visibly different number rather than a subtly different one.
 */
export function buildSeedCorpus(): SpecScenario[] {
  const H = CORPUS_HOUR;
  const W = CORPUS_WINDOW_START;
  const cases: SpecScenario[] = [];

  cases.push(
    scenario('seed/no-seed', [
      song('a', { buckets: [{ hour: H, up: 5, down: 0 }] }),
      song('b'),
    ]),
  );
  cases.push(
    scenario('seed/one-seed-hour', [
      song('a', { seed: seedRun(1, 1.0) }),
      song('b'),
    ]),
  );
  cases.push(
    scenario('seed/full-72-explicit', [
      song('a', { seed: seedRun(72, 0.25) }),
      song('b'),
    ]),
  );
  cases.push(
    scenario('seed/partial-every-third-hour', [
      song('a', {
        seed: [0, 3, 6, 9, 12].map((i) => seedRecord(W + i, 0.5)),
      }),
      song('b'),
    ]),
  );
  cases.push(
    scenario('seed/outside-window-expired-and-future', [
      song('a', { seed: [
        seedRecord(H - 72, 2.0), seedRecord(H + 1, 2.0),
        seedRecord(H - 73, 2.0), seedRecord(H + 2, 2.0),
      ] }),
      song('b'),
    ]),
  );
  cases.push(
    scenario('seed/at-H-minus-71', [
      song('a', { seed: [seedRecord(W, 1.5)] }),
      song('b'),
    ]),
  );
  cases.push(
    scenario('seed/at-H', [
      song('a', { seed: [seedRecord(H, 1.5)] }),
      song('b'),
    ]),
  );
  cases.push(
    scenario('seed/at-H-minus-72-expired', [
      song('a', { seed: [seedRecord(H - 72, 1.5)] }),
      song('b', { buckets: [{ hour: H, up: 5, down: 0 }] }),
    ]),
  );
  cases.push(
    scenario('seed/actual-overrides-seed', [
      song('a', {
        buckets: [{ hour: H, up: 5, down: 0 }],
        seed: [seedRecord(H, 1.0)],
      }),
      song('b', { seed: [seedRecord(H, 1.0)] }),
    ]),
  );
  cases.push(
    scenario('seed/actual-zero-overrides-seed', [
      song('a', {
        buckets: [{ hour: H, up: 0, down: 0 }],
        seed: [seedRecord(H, 2.0)],
      }),
      song('b', { seed: [seedRecord(H, 2.0)] }),
    ]),
  );
  cases.push(
    scenario('seed/non-uniform-profile', [
      song('a', { seed: [
        seedRecord(H - 10, 1.0), seedRecord(H - 9, 0.5),
        seedRecord(H - 8, 1.8), seedRecord(H, 0.25),
      ] }),
      song('b', { seed: seedRun(72, 0.1) }),
    ]),
  );
  cases.push(
    scenario('seed/archived-records-do-not-contribute', [
      song('a', { seed: [
        seedRecord(H - 2, 2.0, true), seedRecord(H - 1, 2.0, false),
      ] }),
      song('b'),
    ]),
  );
  cases.push(
    scenario('seed/actual-source-record-is-not-seed', [
      song('a', { seed: [
        { hour: H, c: 2.0, source: 'ACTUAL', archived: false },
      ] }),
      song('b'),
    ]),
  );
  cases.push(
    scenario('seed/extreme-nonuniform', [
      song('a', { seed: [
        seedRecord(H - 3, 1e-15), seedRecord(H - 2, 2),
        seedRecord(H - 1, 0.1), seedRecord(H, 1.9999999999),
      ] }),
      song('b', { seed: seedRun(72, 0.3333333333333333) }),
    ]),
  );

  return cases;
}
/** Platform activity across all three platforms for one song. */
export function withPlatforms(
  s: SpecSong,
  yt: number,
  sp: number,
  bp: number,
  hour = CORPUS_HOUR,
): SpecSong {
  return {
    ...s,
    youtube: [{ hour, value: yt }],
    spotify: [{ hour, value: sp }],
    boomplay: [{ hour, value: bp }],
  };
}

/** Kura, platform, ranking, and lifecycle cases. */
export function buildRemainingCorpus(): SpecScenario[] {
  const H = CORPUS_HOUR;
  const cases: SpecScenario[] = [];

  // -- PERSISTENT KURA --------------------------------------------------------
  for (const [label, kura] of [
    ['zero', 0],
    ['small', 0.5],
    ['medium', 42],
    ['large', 100000],
  ] as const) {
    for (const [cl, closed] of [['no-cycle', null], ['cycle-0', 0], ['cycle-1', 1], ['cycle-2', 2]] as const) {
      cases.push(
        scenario(`kura/${label}-${cl}`, [
          songWithC('a', 3, 7, kura),
          songWithC('b', 5, 9, kura),
        ], closed),
      );
    }
  }

  // -- PLATFORMS --------------------------------------------------------------
  cases.push(
    scenario('platform/all-idle', [
      withPlatforms(songWithC('a', 2), 0, 0, 0),
      withPlatforms(songWithC('b', 3), 0, 0, 0),
    ]),
  );
  cases.push(
    scenario('platform/youtube-only', [
      withPlatforms(songWithC('a', 2), 10, 0, 0),
      withPlatforms(songWithC('b', 3), 30, 0, 0),
    ]),
  );
  cases.push(
    scenario('platform/two-active', [
      withPlatforms(songWithC('a', 2), 10, 5, 0),
      withPlatforms(songWithC('b', 3), 30, 1, 0),
    ]),
  );
  cases.push(
    scenario('platform/all-active', [
      withPlatforms(songWithC('a', 2), 10, 5, 2),
      withPlatforms(songWithC('b', 3), 30, 1, 6),
      withPlatforms(songWithC('c', 4), 1, 1, 1),
    ]),
  );
  cases.push(
    scenario('platform/tied-activity', [
      withPlatforms(songWithC('a', 2), 7, 7, 7),
      withPlatforms(songWithC('b', 3), 7, 7, 7),
    ]),
  );
  cases.push(
    scenario('platform/extreme-ratio', [
      withPlatforms(songWithC('a', 2), 1e12, 1, 1),
      withPlatforms(songWithC('b', 3), 1e-6, 1e-6, 1e-6),
    ]),
  );
  cases.push(
    scenario('platform/outside-168h-window', [
      withPlatforms(songWithC('a', 2), 100, 0, 0, H - 168),
      withPlatforms(songWithC('b', 3), 0, 50, 0, H),
      withPlatforms(songWithC('c', 4), 0, 0, 5, H - 167),
    ]),
  );

  // -- RANKING ----------------------------------------------------------------
  cases.push(
    scenario('rank/exact-score-ties-broken-by-k', [
      songWithC('a', 2, 100),
      songWithC('b', 2, 200),
      songWithC('c', 2, 200),
    ]),
  );
  cases.push(
    scenario('rank/k-ties-broken-by-platform', [
      withPlatforms(songWithC('a', 2, 50), 10, 10, 10),
      withPlatforms(songWithC('b', 2, 50), 20, 20, 20),
    ]),
  );
  cases.push(
    scenario('rank/songid-tiebreak', [
      songWithC('delta', 2, 50),
      songWithC('alpha', 2, 50),
      songWithC('charlie', 2, 50),
      songWithC('bravo', 2, 50),
    ]),
  );
  cases.push(
    scenario('rank/identical-except-id', [
      songWithC('zzz', 4, 7, 3),
      songWithC('aaa', 4, 7, 3),
      songWithC('mmm', 4, 7, 3),
    ]),
  );
  cases.push(
    scenario('rank/identical-except-id-utf16', [
      songWithC('Z', 1, 1, 1), songWithC('a', 1, 1, 1),
      songWithC('A', 1, 1, 1), songWithC('0', 1, 1, 1),
    ]),
  );

  // -- LIFECYCLE --------------------------------------------------------------
  cases.push(
    scenario('lifecycle/vaulted-excluded', [
      songWithC('a', 3, 10),
      song('b', { lifecycle: 'VAULT', k: 999, persistentKura: 500,
        buckets: fullTwoBuckets(50) }),
    ]),
  );
  cases.push(
    scenario('lifecycle/all-vaulted', [
      song('a', { lifecycle: 'VAULT', k: 1, persistentKura: 10, buckets: fullTwoBuckets(5) }),
      song('b', { lifecycle: 'VAULT', k: 2, persistentKura: 20, buckets: fullTwoBuckets(6) }),
    ]),
  );
  cases.push(
    scenario('lifecycle/zero-c-active-vs-vaulted', [
      song('zero-c-active', { buckets: [] }),
      song('vaulted-with-activity', { lifecycle: 'VAULT', buckets: fullTwoBuckets(40) }),
    ]),
  );
  cases.push(
    scenario('lifecycle/vault-then-restore', [
      song('a', { persistentKura: 0, buckets: fullTwoBuckets(4), k: 11 }),
      song('b', { persistentKura: 0, buckets: fullTwoBuckets(6), k: 22 }),
    ]),
  );

  return cases;
}

/** Every deterministic case, in a stable order. */
export function allCorpus(): SpecScenario[] {
  return [...buildCorpus(), ...buildSeedCorpus(), ...buildRemainingCorpus()];
}
export function buildRandomCorpus(seed: number, count: number): SpecScenario[] {
  const H = CORPUS_HOUR;
  const W = CORPUS_WINDOW_START;
  const rng = makeRng(seed);
  const cases: SpecScenario[] = [];

  const voteChoices = [0, 1, 2, 3, 4, 5, 6, 7, 12, 40];
  const downChoices = [0, 0, 0, 1, 2, 3, 4, 5, 9];
  // Seeded C is kept inside [0, C_MAX] = [0, 2]. Values above C_MAX are
  // accepted by chart evaluation but rejected by the rollover's decay layer,
  // which validates closedHourC against [0, C_MAX]. That split is recorded as
  // discrepancy D-001; a generator that emitted such values would test that
  // inconsistency on every run instead of the mathematics.
  const seedChoices = [0, 0.25, 0.5, 1, 1.5, 2, 0.001, 0.125];

  for (let i = 0; i < count; i++) {
    const songCount = rngInt(rng, 6); // 0..5 songs
    const songs: SpecSong[] = [];

    for (let s = 0; s < songCount; s++) {
      const buckets: SpecBucket[] = [];
      const bucketCount = rngInt(rng, 8);
      const occupied = new Set<number>();
      for (let b = 0; b < bucketCount; b++) {
        const hour = W + rngInt(rng, 72);
        if (occupied.has(hour)) continue; // duplicates are a data defect; skip
        occupied.add(hour);
        buckets.push({
          hour,
          up: voteChoices[rngInt(rng, voteChoices.length)]!,
          down: downChoices[rngInt(rng, downChoices.length)]!,
        });
      }

      const seedRecords: SpecSeed[] = [];
      const seedCount = rngInt(rng, 6);
      const seeded = new Set<number>();
      for (let k = 0; k < seedCount; k++) {
        const hour = W + rngInt(rng, 72);
        if (seeded.has(hour)) continue;
        seeded.add(hour);
        seedRecords.push(seedRecord(hour, seedChoices[rngInt(rng, seedChoices.length)]!));
      }

      const platformValue = (): number => rngInt(rng, 5) * (rngInt(rng, 4) + 1);

      // Observations at DISTINCT hours. Two records for the same (platform,
      // clock hour) are DUPLICATE_HOUR_INDEX to the engine, because summing
      // them would invent performance that was never measured - so a generator
      // that emitted collisions would be testing a rejection path rather than
      // the mathematics.
      const distinctObservations = (): SpecObservation[] => {
        const hours = new Set<number>();
        const out: SpecObservation[] = [];
        const wanted = rngInt(rng, 3);
        for (let j = 0; j < wanted; j++) {
          const hour = H + rngInt(rng, 4);
          if (hours.has(hour)) continue;
          hours.add(hour);
          out.push(observation(hour, platformValue()));
        }
        return out;
      };

      songs.push(
        song(`s${s}`, {
          lifecycle: rngInt(rng, 5) === 0 ? 'VAULT' : 'ACTIVE',
          k: rngInt(rng, 1000),
          persistentKura: rngInt(rng, 20) * 5,
          buckets,
          seed: seedRecords,
          youtube: distinctObservations(),
          spotify: distinctObservations(),
          boomplay: distinctObservations(),
        }),
      );
    }

    const closedChoice = rngInt(rng, 5);
    const closedHourC =
      closedChoice === 0 ? null : [0, 0.5, 1, 1.5, 2][closedChoice - 1]!;

    cases.push(scenario(`random/seed${seed}-case${i}`, songs, closedHourC));
  }

  return cases;
}