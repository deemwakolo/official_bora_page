/** One song with sensible defaults; override only what a case is about. */
export function song(id: string, overrides: Partial<SpecSong> = {}): SpecSong {
  return {
    id,
    lifecycle: 'ACTIVE',
    k: 0,
    persistentKura: 0,
    buckets: [],
    seed: [],
    youtube: [],
    spotify: [],
    boomplay: [],
    ...overrides,
  };
}

/** A bucket whose votes cross the 4/5 tier boundary deliberately. */
export function bucket(hour: number, up: number, down = 0): SpecBucket {
  return { hour, up, down };
}

/** A SEED record with an explicit provenance. */
export function seedRecord(hour: number, c: number, archived = false): SpecSeed {
  return { hour, c, source: 'SEED', archived };
}

export function observation(hour: number, value: number): SpecObservation {
  return { hour, value };
}

/** A SEED record placed exactly on hour H. */
export function seedAt(hour: number, c: number): SpecSeed {
  return seedRecord(hour, c);
}

