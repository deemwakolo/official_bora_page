/**
 * BORA — PHASE 21 DETERMINISTIC CASE GENERATOR
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * ── DETERMINISM IS A REQUIREMENT, NOT A CONVENIENCE (Phase 21 §17, §27) ────────
 *
 * Every case here is a pure function of an integer seed. There is no
 * `Math.random`, no system entropy, and no wall clock, so the entire corpus is
 * byte-reproducible across runs and machines. A conformance suite that drew
 * fresh inputs each run could not demonstrate reproducibility, and a failure
 * could not be replayed.
 *
 * ── NO PROPERTY-TESTING DEPENDENCY ────────────────────────────────────────────
 *
 * The corpus is generated by hand-written code below. Adding a property-testing
 * library for this phase would change the project's dependency surface to buy
 * a shrinking algorithm, and would risk adopting the SAME shrinking logic the
 * engine's own generators use — which is precisely the shared-helper failure
 * this phase exists to prevent.
 *
 * ── WHAT THE CORPUS COVERS (Phase 21 §17) ─────────────────────────────────────
 *
 *   population      0, 1, 2, 5, 10 songs
 *   hourly C        all-zero, one active hour, full 2.0, 0.5, 1.0, 1.5, mixed,
 *                   extreme vote counts
 *   window          exactly 72, 71, 73 hours, sparse, boundary H−71, expired
 *                   H−72, future H+1
 *   seed            none, single hour, full 72, partial, outside window, at
 *                   H−71 / H / H−72, actual overrides seed, actual C=0
 *                   overrides seed, non-uniform profile
 *   Kura            zero, small, large finite
 *   platforms       idle, one active, two active, all active, tied, extreme
 *   ranking         score ties, K ties, platform ties, songId tie-break
 *   lifecycle       active, vaulted, restore, repeated vault/restore
 */

import type {
  SpecBucket,
  SpecScenario,
  SpecSeed,
  SpecSong,
  SpecObservation,
} from './spec';

/**
 * A 32-bit linear congruential generator.
 *
 * Chosen over anything cleverer because an oracle should be obvious. Its whole
 * body is one line of arithmetic, so a reviewer can confirm by inspection that
 * it is reproducible and carries no hidden state.
 */
export function makeRng(seed: number): () => number {
  let state = seed >>> 0;
  return function next(): number {
    // Numerical Recipes LCG constants — 32-bit, full period.
    state = (Math.imul(1664525, state) + 1013904223) >>> 0;
    return state / 4294967296;
  };
}

/** A deterministic integer in [0, bound). */
export function rngInt(rng: () => number, bound: number): number {
  return Math.floor(rng() * bound) % bound;
}

/** A deterministic element of a list. */
export function rngPick<T>(rng: () => number, list: readonly T[]): T {
  return list[rngInt(rng, list.length)]!;
}

/**
 * A deterministic Fisher–Yates shuffle.
 *
 * Used only by the metamorphic properties (P1, P2) to build permuted inputs.
 * It is NOT used to randomise the corpus: corpus variety comes from the seed,
 * so that a failing case number always names the same case.
 */
export function shuffle<T>(rng: () => number, list: readonly T[]): T[] {
  const out = [...list];
  for (let i = out.length - 1; i > 0; i--) {
    const j = rngInt(rng, i + 1);
    const a = out[i]!;
    const b = out[j]!;
    out[i] = b;
    out[j] = a;
  }
  return out;
}

